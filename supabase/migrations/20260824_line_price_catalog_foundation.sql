-- =============================================================
-- LINE-ASSIST-009 — Mitang internal price catalog foundation (Pricing V1)
--
-- Authoritative, deterministic price lookup for INTERNAL employee/work groups.
-- There is no AI, no NLU, no n8n and no external call anywhere in this path: a
-- query is normalized, matched against a seeded alias table by longest literal
-- alias, and answered from seeded catalog rows.
--
-- Scope model
-- -----------
--   scope='global'  -> country_code IS NULL, applies to every nationality
--   scope='country' -> country_code IS NOT NULL (only 'LA' is seeded in V1)
-- Adding Myanmar ('MM') or Cambodia ('KH') later needs new rows only; no schema
-- change. They are deliberately NOT seeded here.
--
-- Cost model
-- ----------
-- Costs live in a child table, never in prose, so lookup stays deterministic:
--   * ordinary service        -> exactly one cost row, location_key IS NULL
--   * แจ้งเข้า (แจ้งออกตาย)  -> three cost rows, one per province
--   * ขึ้นทะเบียนใหม่         -> ZERO cost rows and cost_status='unknown'
-- cost_status='unknown' can therefore never surface a fabricated number: there
-- is no row to read, and the lookup returns a null cost with the status intact.
--
-- This migration adds pricing tables, one immutable normalizer and one narrow
-- read RPC. It touches no existing table, no customer data, no LINE operating
-- mode, no router, no scheduler and no Edge Function.
--
-- Fail-closed
-- -----------
-- This is a first-time foundation, so it refuses to run against unexpected prior
-- state instead of absorbing it. The preflight below aborts if any intended
-- pricing object already exists, every CREATE is a plain CREATE rather than
-- IF NOT EXISTS or OR REPLACE, and the seeds carry no ON CONFLICT clause: a seed
-- that cannot be inserted exactly is an error. Nothing here inspects, drops,
-- reconciles or repairs anything outside the pricing objects it creates.
-- =============================================================

-- -------------------------------------------------------------
-- Preflight — abort on any pre-existing pricing object
-- -------------------------------------------------------------

do $preflight$
declare
  v_existing text;
begin
  select pg_catalog.string_agg(t.obj, ', ' order by t.obj)
    into v_existing
    from (
      select 'table public.line_price_services' as obj
       where pg_catalog.to_regclass('public.line_price_services') is not null
      union all
      select 'table public.line_price_service_costs'
       where pg_catalog.to_regclass('public.line_price_service_costs') is not null
      union all
      select 'table public.line_price_service_aliases'
       where pg_catalog.to_regclass('public.line_price_service_aliases') is not null
      union all
      select 'function public.line_price_normalize(text)'
       where pg_catalog.to_regprocedure('public.line_price_normalize(text)') is not null
      union all
      select 'function public.app_lookup_line_price(text)'
       where pg_catalog.to_regprocedure('public.app_lookup_line_price(text)') is not null
    ) as t;

  -- Deliberately reports every conflicting object at once and changes none of
  -- them. Reconciliation is an Owner decision, not a migration side effect.
  if v_existing is not null then
    raise exception using
      errcode = '42710',
      message = 'pricing foundation preflight failed: already present: ' || v_existing,
      hint = 'This migration builds the pricing foundation from scratch. Investigate the existing objects; do not drop or reconcile them here.';
  end if;
end
$preflight$;

-- -------------------------------------------------------------
-- Query normalizer
-- -------------------------------------------------------------

-- Folds case and strips everything that is not a digit, a latin letter or a Thai
-- character, so spacing, punctuation and dashes cannot change a match. Written
-- as IMMUTABLE so stored aliases can be constrained to already-normal form.
-- '45-60 วัน' and '45–60วัน' both normalize to '4560วัน'.
create function public.line_price_normalize(p_text text)
returns text
language sql
immutable
set search_path = ''
as $$
  select coalesce(
    pg_catalog.regexp_replace(pg_catalog.lower(p_text), '[^0-9a-zก-๙]', '', 'g'),
    ''
  );
$$;

comment on function public.line_price_normalize(text) is
  'Deterministic price-query normalizer: lowercases and removes every character that is not a digit, latin letter or Thai character. Immutable so alias rows can be constrained to normal form.';

-- -------------------------------------------------------------
-- Catalog
-- -------------------------------------------------------------

create table public.line_price_services (
  id              bigint generated by default as identity primary key,
  service_key     text not null unique,
  service_name    text not null,
  variant_name    text null,
  scope           text not null,
  country_code    text null,
  country_name    text null,
  sale_price_min  numeric(12,2) not null,
  sale_price_max  numeric(12,2) not null,
  cost_status     text not null,
  note            text null,
  is_active       boolean not null default true,
  sort_order      integer not null default 0,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now(),
  constraint line_price_services_scope_check
    check (scope in ('global', 'country')),
  constraint line_price_services_cost_status_check
    check (cost_status in ('confirmed', 'unknown')),
  -- A global row must carry no country at all; a country row must carry both the
  -- code and its display name. This is what keeps 'global' unambiguous.
  constraint line_price_services_country_scope_check
    check (
      (scope = 'global' and country_code is null and country_name is null)
      or (scope = 'country' and country_code is not null and country_name is not null)
    ),
  constraint line_price_services_country_code_check
    check (country_code is null or country_code ~ '^[A-Z]{2}$'),
  constraint line_price_services_sale_range_check
    check (sale_price_min >= 0 and sale_price_max >= sale_price_min)
);

comment on table public.line_price_services is
  'Internal Mitang price catalog. Sale range is authoritative here; confirmed costs live in line_price_service_costs. Contains no customer data.';
comment on column public.line_price_services.cost_status is
  'confirmed = at least one cost row exists; unknown = cost is not confirmed and NO cost row exists, so no number can be fabricated.';
comment on column public.line_price_services.variant_name is
  'Human-readable variant qualifier such as a turnaround window; null when the service has no variant.';

create index idx_line_price_services_active
  on public.line_price_services (sort_order, id)
  where is_active;

-- -------------------------------------------------------------
-- Costs (child)
-- -------------------------------------------------------------

create table public.line_price_service_costs (
  id                   bigint generated by default as identity primary key,
  service_id           bigint not null
                       references public.line_price_services(id) on delete cascade,
  location_key         text null,
  location_name        text null,
  location_match_norms text[] not null default '{}',
  cost_amount          numeric(12,2) not null,
  sort_order           integer not null default 0,
  created_at           timestamptz not null default now(),
  updated_at           timestamptz not null default now(),
  constraint line_price_service_costs_amount_check
    check (cost_amount >= 0),
  -- Either this is the service's single cost (no location at all), or it is a
  -- location variant and must carry a key, a display name and at least one
  -- normalized match token. Half-populated location rows cannot exist.
  constraint line_price_service_costs_location_check
    check (
      (location_key is null
        and location_name is null
        and pg_catalog.cardinality(location_match_norms) = 0)
      or (location_key is not null
        and location_name is not null
        and pg_catalog.cardinality(location_match_norms) >= 1)
    )
);

comment on table public.line_price_service_costs is
  'Confirmed internal cost rows. A service either has one location-free cost row, or several location-specific rows. A service with cost_status=unknown has none.';
comment on column public.line_price_service_costs.location_match_norms is
  'Normalized tokens that select this location variant when they appear in a query, e.g. {กทม,กรุงเทพ}. Matching is literal containment only.';

-- One location-free cost per service.
create unique index uq_line_price_service_costs_single
  on public.line_price_service_costs (service_id)
  where location_key is null;

-- One cost per (service, location) for location-specific services.
create unique index uq_line_price_service_costs_location
  on public.line_price_service_costs (service_id, location_key)
  where location_key is not null;

create index idx_line_price_service_costs_service
  on public.line_price_service_costs (service_id, sort_order, id);

-- -------------------------------------------------------------
-- Aliases
-- -------------------------------------------------------------

-- Deterministic lookup keys. Several catalog rows MAY share one generic alias on
-- purpose: 'พาสลาว' is attached to both Laos passport variants so a generic
-- question returns both, while the longer 'พาสลาวด่วน' is attached only to the
-- express row. Because the RPC keeps only the longest matching alias, a more
-- specific alias always beats the generic one without any ranking column.
create table public.line_price_service_aliases (
  id         bigint generated by default as identity primary key,
  service_id bigint not null
             references public.line_price_services(id) on delete cascade,
  alias_norm text not null,
  is_active  boolean not null default true,
  created_at timestamptz not null default now(),
  constraint line_price_service_aliases_norm_check
    check (alias_norm <> '' and alias_norm = public.line_price_normalize(alias_norm))
);

comment on table public.line_price_service_aliases is
  'Normalized lookup aliases. alias_norm is constrained to already-normal form so a query normalized the same way can be matched by literal containment.';

create unique index uq_line_price_service_aliases_pair
  on public.line_price_service_aliases (alias_norm, service_id);

create index idx_line_price_service_aliases_norm
  on public.line_price_service_aliases (alias_norm)
  where is_active;


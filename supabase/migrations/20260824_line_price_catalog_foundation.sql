-- -------------------------------------------------------------
-- Lookup RPC
-- -------------------------------------------------------------

-- One row per (service, cost). A service with no cost row still returns exactly
-- one row carrying a null cost and cost_status='unknown', so the caller can say
-- "ยังไม่ยืนยัน" without inventing a figure. No customer, case, document or
-- registry data is reachable from here.
create function public.app_lookup_line_price(p_query text)
returns table (
  service_key     text,
  service_name    text,
  variant_name    text,
  scope           text,
  country_code    text,
  cost_status     text,
  location_name   text,
  cost_amount     numeric,
  sale_price_min  numeric,
  sale_price_max  numeric,
  note            text
)
language sql
stable
security definer
set search_path = ''
as $$
  with q as (
    select public.line_price_normalize(p_query) as norm
  ),
  hit as (
    -- Every alias literally contained in the normalized query.
    select a.service_id,
           pg_catalog.length(a.alias_norm) as alias_len
      from public.line_price_service_aliases a
     cross join q
     where a.is_active
       and q.norm <> ''
       and pg_catalog.strpos(q.norm, a.alias_norm) > 0
  ),
  matched as (
    -- Keep only the longest alias. Ties are intentional: a generic alias shared
    -- by several variants returns all of them.
    select distinct h.service_id
      from hit h
     where h.alias_len = (select pg_catalog.max(h2.alias_len) from hit h2)
  ),
  svc as (
    select s.*
      from public.line_price_services s
      join matched m on m.service_id = s.id
     where s.is_active
  ),
  loc as (
    -- Location variants this query explicitly names.
    select c.id as cost_id, c.service_id
      from public.line_price_service_costs c
     cross join q
     where c.location_key is not null
       and exists (
         select 1
           from pg_catalog.unnest(c.location_match_norms) as t(token)
          where pg_catalog.strpos(q.norm, t.token) > 0
       )
  )
  select s.service_key,
         s.service_name,
         s.variant_name,
         s.scope,
         s.country_code,
         s.cost_status,
         c.location_name,
         c.cost_amount,
         s.sale_price_min,
         s.sale_price_max,
         s.note
    from svc s
    left join public.line_price_service_costs c
      on c.service_id = s.id
   where c.id is null
      -- No province named: return every cost variant, never guess one.
      or not exists (select 1 from loc l where l.service_id = s.id)
      -- Province named: return only the variants it names.
      or exists (select 1 from loc l where l.cost_id = c.id)
   order by s.sort_order, s.id, c.sort_order nulls first, c.id;
$$;

comment on function public.app_lookup_line_price(text) is
  'Deterministic internal price lookup. Normalizes the query, keeps the longest matching alias, and returns one row per matching service and cost. Returns zero rows when nothing matches. Exposes pricing facts only: no customer, case, document or LINE registry data, and no AI or external call.';

